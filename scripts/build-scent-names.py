"""Scent number -> individual scent name for the Bundle & Save picker rows ("318" -> "Toffee Embrace").

Source: the MAGYX Whop store's name list, magyx-whop scripts/product-names.json
({handle: {"from": "Smells like ... - No. 318", "to": "Toffee Embrace - No. 318"}}). Writes snippets/mgx-scent-name.liquid,
a Liquid `case` on the normalized number (leading zeros and case ignored: "034" = "34", "219M" = "219m").
The product titles on magyx.co stay as they are; only the picker shows the names.

Stops without writing when an entry is not "<Name> - No. <number>" or a number appears twice.

Usage: py scripts/build-scent-names.py [path/to/product-names.json]
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SRC = os.path.join(os.path.expanduser('~'), 'Documents', 'dev', 'magyx-whop-bundle-save', 'scripts', 'product-names.json')
OUT = os.path.join(ROOT, 'snippets', 'mgx-scent-name.liquid')
ENTRY = re.compile(r'^(?P<name>.+?)\s+-\s+No\.\s*(?P<digits>\d+)(?P<letter>[A-Za-z]?)\s*$')


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC
    data = json.load(open(src, encoding='utf-8'))
    names, errors = {}, []
    for handle, entry in data.items():
        m = ENTRY.match(str(entry.get('to', '')))
        if not m:
            errors.append(f'{handle}: "{entry.get("to")}" is not "<Name> - No. <number>"')
            continue
        key = str(int(m.group('digits'))) + m.group('letter').lower()
        name = m.group('name').strip()
        if key in names and names[key] != name:
            errors.append(f'number {key} twice: "{names[key]}" and "{name}"')
        names[key] = name
    if errors:
        print('Nothing written:\n  ' + '\n  '.join(errors))
        sys.exit(1)
    for name in names.values():
        if "'" in name and '"' in name:
            print(f'Nothing written: "{name}" has both quote kinds')
            sys.exit(1)

    def quote(s):
        return f'"{s}"' if "'" in s else f"'{s}'"

    def order(k):
        m = re.match(r'(\d+)(.*)', k)
        return (int(m.group(1)), m.group(2))

    lines = [
        '{%- comment -%}',
        '  mgx-scent-name: individual scent name for a scent number ("318" -> "Toffee Embrace"), used by the',
        '  Bundle & Save picker rows (sections/pm-bundle-save.liquid). Prints nothing for an unknown number.',
        '  GENERATED by scripts/build-scent-names.py from the MAGYX Whop store\'s scripts/product-names.json.',
        '  Do not edit by hand: change the source list and rerun the script.',
        "  Usage: capture the output of render 'mgx-scent-name', number: '034'",
        '  number: digits plus an optional letter; leading zeros and case are ignored ("034" = "34", "219M" = "219m").',
        '{%- endcomment -%}',
        '{%- liquid',
        '  assign mgx_n = number | strip | downcase',
        "  assign mgx_letter = ''",
        '  assign mgx_last = mgx_n | slice: -1, 1',
        "  if mgx_last != blank and 'abcdefghijklmnopqrstuvwxyz' contains mgx_last",
        '    assign mgx_letter = mgx_last',
        '    assign mgx_cut = mgx_n.size | minus: 1',
        '    assign mgx_n = mgx_n | slice: 0, mgx_cut',
        '  endif',
        '  assign mgx_key = mgx_n | plus: 0 | append: mgx_letter',
        '  case mgx_key',
    ]
    for key in sorted(names, key=order):
        lines.append(f'    when {quote(key)}')
        lines.append(f'      echo {quote(names[key])}')
    lines += ['  endcase', '-%}', '']
    with open(OUT, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write('\n'.join(lines))
    print(f'{os.path.relpath(OUT, ROOT)}: {len(names)} names from {src}')


if __name__ == '__main__':
    main()
